package operators;

public class Operators {
    static void main(String[] args) {
        // The operator '+' to add together two values
        int num2 = 10 +20;
        int num3 = num2 + 100;
        int num4 = num3 + 129;

        System.out.println(num2);
        System.out.println(num3);
        System.out.println(num4);
    }
}
