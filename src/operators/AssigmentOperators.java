package operators;

public class AssigmentOperators {
    static void main(String[] args) {
        // The addition assigment operator (+=) adds value to a variable
        int a = 10;
        a += 7;

        System.out.println(a);

        // operators are just shorter ways of writing code x = x +5 -> x +=5;

        // Real Life: Tracking Savings
        int savings = 100;
        savings += 50;

        System.out.println("Total savings: " + savings);

    }
}
